PKG_DIR = Path(__file__).resolve().parent
BOOT_FILES = ("__init__.py", "canon.py", "recorder.py", "replayer.py", "targets.py")

SITECUSTOMIZE = '''\
# Generated by refactor-anything: starts the recorder, then hands over to any other sitecustomize.
import importlib, os, sys
_here = os.path.dirname(os.path.abspath(__file__))
try:
    from refactor_anything import recorder as _ra_recorder
    _ra_recorder.start()
except Exception as _ra_exc:  # never break the program being recorded
    sys.stderr.write("refactor-anything: recorder not started: %r\\n" % (_ra_exc,))
_ra_saved = list(sys.path)
sys.modules.pop("sitecustomize", None)
sys.path[:] = [p for p in sys.path if os.path.abspath(p or os.curdir) != _here]
try:
    importlib.import_module("sitecustomize")
except ImportError:
    pass
finally:
    sys.path[:] = _ra_saved
'''


class RecordError(RuntimeError):
    pass


def make_boot(dest: Path, *, sitecustomize: bool) -> Path:
    """A self-contained copy of the runtime modules (stdlib only) for the user's interpreter."""
    pkg = dest / "refactor_anything"
    pkg.mkdir(parents=True, exist_ok=True)
    for name in BOOT_FILES:
        shutil.copyfile(PKG_DIR / name, pkg / name)
    if sitecustomize:
        (dest / "sitecustomize.py").write_text(SITECUSTOMIZE, encoding="utf-8")
    return dest


def _git(root: Path, *args: str) -> str | None:
    try:
        p = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True, timeout=10)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return p.stdout.strip() if p.returncode == 0 else None


# -- replay ------------------------------------------------------------------------------

@dataclass
class ReplayRun:
    results: list[dict[str, Any]]
    error: str | None = None
    seconds: float = 0.0
    timed_out: bool = False


def replay(lock: Lock, cases: list[dict[str, Any]], *, mutant: dict[str, Any] | None = None,
           timeout: float = 600.0, python: str | None = None, memory_mb: int | None = None,
           fill: bool = False) -> ReplayRun:
    if not cases:
        return ReplayRun([])
    py = python or lock.python or sys.executable
    with tempfile.TemporaryDirectory(prefix="refactor-anything-") as tmp:
        t = Path(tmp)
        boot = make_boot(t / "boot", sitecustomize=False)
        job = {"root": str(lock.root), "sys_path": lock.abs_sys_path(), "cases": cases, "mutant": mutant,
               "memory_mb": memory_mb, "fill": fill}
        (t / "job.json").write_text(json.dumps(job), encoding="utf-8")
        env = {k: v for k, v in os.environ.items() if k != ENV}
        env.setdefault("PYTHONIOENCODING", "utf-8")
        try:
            subprocess.run([py, str(boot / "refactor_anything" / "replayer.py"), str(t / "job.json"), str(t / "result.json")],
                           cwd=lock.root, env=env, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                           stderr=subprocess.PIPE, timeout=timeout)
        except subprocess.TimeoutExpired:
            return ReplayRun([], error=f"replay did not finish within {timeout:g}s", timed_out=True)
        except OSError as exc:
            return ReplayRun([], error=f"cannot start {py}: {exc}")
        out_path = t / "result.json"
        if not out_path.exists():
            return ReplayRun([], error="replay process exited without a result (crashed or killed)")
        data = json.loads(out_path.read_text(encoding="utf-8"))
    return ReplayRun(data.get("results", []), data.get("error"), float(data.get("seconds", 0.0)))


# -- record ------------------------------------------------------------------------------

@dataclass
class RecordSummary:
    exit_code: int
    new_cases: int
    unstable: int
    per_key: dict[str, dict[str, int]]
    notes: dict[str, str]
    never_called: list[str]


def record(root: Path, targets: list[Target], command: list[str], *, cap: int = 200, private: bool = False,
           fresh: bool = False, python: str | None = None) -> RecordSummary:
    root = root.resolve()
    if not command:
        raise RecordError("give the command to record after --, e.g. -- python -m pytest -q")
    lock = Lock(root)
    if Lock.exists(root) and not fresh:
        lock = Lock.load(root)
        if lock.tampered():
            raise RecordError("the recorded cases were edited by hand; re-record with --fresh")
        changed = lock.changed_sources()
        if changed:
            # Adding inputs after a refactor is fine as long as the code still honours the lock.
            res = check(root, python=python)
            if not res.ok:
                raise RecordError(
                    "source changed since the lock was recorded (" + ", ".join(changed) + ") and "
                    f"{len(res.failures) or 'some'} recorded calls no longer match. Fix the code until "
                    "`refactor-anything check` passes, or `record --fresh` to accept today's behaviour as the new baseline.")
    elif fresh and (root / store.DIR).exists():
        shutil.rmtree(root / store.DIR)
        lock = Lock(root)
    lock.targets = merge(lock.targets, targets)

    raw_dir = root / store.DIR / "raw"
    if raw_dir.exists():
        shutil.rmtree(raw_dir)
    raw_dir.mkdir(parents=True)
    with tempfile.TemporaryDirectory(prefix="refactor-anything-boot-") as tmp:
        boot = make_boot(Path(tmp), sitecustomize=True)
        env = dict(os.environ)
        env["PATH"] = user_path()  # `python3` in the command must be the user's, not uvx's
        env["PYTHONPATH"] = str(boot) + (os.pathsep + env["PYTHONPATH"] if env.get("PYTHONPATH") else "")
        env[ENV] = json.dumps({"out": str(raw_dir), "cap": cap, "private": private,
                               "targets": [t.to_json() for t in lock.targets]})
        exe = shutil.which(command[0], path=env["PATH"]) or command[0]
        try:
            proc = subprocess.run([exe, *command[1:]], cwd=root, env=env)
        except OSError as exc:
            raise RecordError(f"cannot run {command[0]}: {exc}") from exc

    metas, raw_cases = _read_raw(raw_dir)
    shutil.rmtree(raw_dir, ignore_errors=True)
    instrumented = [m for m in metas if m.get("meta") == "instrumented"]
    if not instrumented and not lock.sources:
        raise RecordError(
            "the command never imported " + ", ".join(t.module for t in targets) +
            " (is it the import name? `python -m pytest` imports from the current directory, a bare `pytest` may not)")

    notes: dict[str, str] = {}
    for m in instrumented:
        module, file_ = m["module"], m.get("file")
        if file_:
            lock.sources[module] = {"file": rel(root, file_), "sha256": sha256_file(Path(file_))}
            base = _import_base(Path(file_), module)
            if base is not None and rel(root, base) not in lock.sys_path:
                lock.sys_path.append(rel(root, base))
        if not lock.python and m.get("python"):
            lock.python = m["python"]
        for k in m.get("keys", []):
            lock.functions.setdefault(k, {})
    for m in metas:
        if m.get("meta") in ("unsupported", "unpicklable", "record-error", "iterator"):
            text = f"{m['meta']}: {m.get('detail', '')}" if m["meta"] != "iterator" else str(m.get("detail", ""))
            if text not in notes.get(m["key"], ""):
                notes[m["key"]] = (notes[m["key"]] + "; " if m["key"] in notes else "") + text
            lock.functions.setdefault(m["key"], {})["note"] = notes[m["key"]]
    if python:
        lock.python = python

    # Merge: dedupe by (key, id) against what is already locked, respect the cap per key.
    have: dict[str, set[str]] = {}
    for module, cases in lock.cases.items():
        for c in cases:
            have.setdefault(c["key"], set()).add(c["id"])
    fresh_cases: list[dict[str, Any]] = []
    for c in raw_cases:
        ids = have.setdefault(c["key"], set())
        if c["id"] in ids or len(ids) >= cap:
            continue
        ids.add(c["id"])
        fresh_cases.append(c)

    tmp_lock = Lock(root, python=lock.python, sys_path=lock.sys_path)
    # Fill: a returned map/zip/islice was not consumed while recording; consume it now, from the same
    # input and the same code, so its items are locked and not just its type.
    to_fill = [c for c in fresh_cases if c.pop("fill", False)]
    if to_fill:
        run = replay(tmp_lock, to_fill, fill=True)
        by_id = {(r["key"], r["id"]): r for r in run.results if r.get("status") == "filled"}
        for c in to_fill:
            r = by_id.get((c["key"], c["id"]))
            if r is not None:
                c.pop("out", None)
                c["gen"], c["after"] = r["gen"], r["after"]
                if r.get("exc"):
                    c["exc"] = r["exc"]
            else:
                note = "returns an iterator whose items could not be replayed: only its type is locked"
                notes.setdefault(c["key"], note)
                lock.functions.setdefault(c["key"], {})["note"] = notes[c["key"]]

    # Stabilise: replay new cases twice, in fresh processes, against the code that produced them.
    unstable_ids: set[tuple[str, str]] = set()
    if fresh_cases:
        for _ in range(2):
            run = replay(tmp_lock, fresh_cases)
            if run.error:
                raise RecordError(f"replay of the fresh recording failed: {run.error}")
            for r in run.results:
                if r["status"] != "pass":
                    unstable_ids.add((r["key"], r["id"]))
    for c in fresh_cases:
        if (c["key"], c["id"]) in unstable_ids:
            c["unstable"] = True
        lock.cases.setdefault(split_key(c["key"])[0], []).append(c)

    lock.commands.append(list(command))
    commit = _git(root, "rev-parse", "HEAD")
    if commit:
        lock.git = {"commit": commit, "dirty": bool(_git(root, "status", "--porcelain"))}
    lock.save()

    per_key: dict[str, dict[str, int]] = {}
    for c in lock.all_cases(stable_only=False):
        d = per_key.setdefault(c["key"], {"cases": 0, "unstable": 0})
        d["unstable" if c.get("unstable") else "cases"] += 1
    never = sorted(k for k in lock.functions if k not in per_key and k not in notes)
    return RecordSummary(proc.returncode, len(fresh_cases), len(unstable_ids), per_key, notes, never)


def _read_raw(raw_dir: Path) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    metas: list[dict[str, Any]] = []
    cases: list[dict[str, Any]] = []
    for f in sorted(raw_dir.glob("*.jsonl")):
        for line in f.read_text(encoding="utf-8").splitlines():
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:  # a process killed mid-write leaves a partial last line
                continue
            (metas if "meta" in rec else cases).append(rec)
    return metas, cases


def _import_base(file_: Path, module: str) -> Path | None:
    """The sys.path entry that made ``module`` importable from ``file_``."""
    parts = module.split(".")
    p = file_.resolve()
    p = p.parent if p.name == "__init__.py" else p.with_suffix("")
    for _ in parts:
        p = p.parent
    return p


# -- check -------------------------------------------------------------------------------

@dataclass
class CheckResult:
    total: int = 0
    passed: int = 0
    failures: list[dict[str, Any]] = field(default_factory=list)
    error: str | None = None
    tampered: bool = False
    changed: list[str] = field(default_factory=list)
    per_key: dict[str, Counter[str]] = field(default_factory=dict)
    unlocked: list[str] = field(default_factory=list)
    seconds: float = 0.0

    @property
    def ok(self) -> bool:
        return not self.error and not self.tampered and not self.failures and self.total > 0

    def to_json(self) -> dict[str, Any]:
        return {"ok": self.ok, "total": self.total, "passed": self.passed, "failed": len(self.failures),
                "error": self.error, "tampered": self.tampered, "changed_modules": self.changed,
                "unlocked": self.unlocked, "seconds": self.seconds,
                "functions": {k: dict(v) for k, v in sorted(self.per_key.items())},
                "failures": self.failures}


def check(root: Path, *, python: str | None = None, timeout: float = 600.0) -> CheckResult:
    lock = Lock.load(root.resolve())
    res = CheckResult(changed=lock.changed_sources())
    if lock.tampered():
        res.tampered = True
        res.error = "the recorded cases in .refactor-anything/cases were changed after recording"
        return res
    cases = lock.all_cases()
    res.total = len(cases)
    locked_keys = {c["key"] for c in cases}
    res.unlocked = sorted(k for k in lock.functions if k not in locked_keys)
    if not cases:
        res.error = "the lock holds no replayable cases"
        return res
    run = replay(lock, cases, python=python, timeout=timeout)
    res.seconds = run.seconds
    if run.error:
        res.error = run.error
        return res
    for r in run.results:
        res.per_key.setdefault(r["key"], Counter())[r["status"]] += 1
        if r["status"] == "pass":
            res.passed += 1
        else:
            res.failures.append(r)
    return res

